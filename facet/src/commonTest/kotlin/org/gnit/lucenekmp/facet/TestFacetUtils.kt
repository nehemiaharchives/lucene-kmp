package org.gnit.lucenekmp.facet

import org.gnit.lucenekmp.document.Document
import org.gnit.lucenekmp.document.Field
import org.gnit.lucenekmp.document.NumericDocValuesField
import org.gnit.lucenekmp.document.StringField
import org.gnit.lucenekmp.index.DocValues
import org.gnit.lucenekmp.index.Term
import org.gnit.lucenekmp.search.DocIdSetIterator
import org.gnit.lucenekmp.search.MatchAllDocsQuery
import org.gnit.lucenekmp.tests.index.RandomIndexWriter
import org.gnit.lucenekmp.tests.util.LuceneTestCase
import org.gnit.lucenekmp.util.FixedBitSet
import org.gnit.lucenekmp.util.IOUtils
import kotlin.test.Test
import kotlin.test.assertTrue

class TestFacetUtils : LuceneTestCase() {
    @Test
    fun testBasic() {
        val dir = newDirectory()
        val writer = RandomIndexWriter(random(), dir)
        val maxDocs = 256

        // Create up to maxDocs number of documents with (id, val) fields having
        // string and numeric representation of the same value
        for (i in 0 until maxDocs) {
            val doc = Document()
            doc.add(StringField("id", i.toString(), Field.Store.NO))
            doc.add(NumericDocValuesField("val", i.toLong()))
            writer.addDocument(doc)
        }

        // Pick a random number of docs to delete.
        // Actual deleted docs might be less than this because
        // of duplicates generated by random()
        val numDocsToDelete = random().nextInt(maxDocs)
        val deletedDocs = FixedBitSet(maxDocs)

        // Delete a random number of randomly picked documents
        // Record what we deleted to make sure we don't find them
        // during iteration
        var actualDocsDeleted = 0
        for (i in 0 until numDocsToDelete) {
            val deletedDocId = random().nextInt(maxDocs)
            if (deletedDocs.get(deletedDocId) == true) {
                // we already deleted and recorded this doc-id
                continue
            }
            deletedDocs.set(deletedDocId)
            writer.deleteDocuments(Term("id", deletedDocId.toString()))
            actualDocsDeleted++
        }

        val searcher = newSearcher(writer.reader)
        val fc = searcher.search(MatchAllDocsQuery(), FacetsCollectorManager())!!

        var visitedDocs = 0
        var disi: DocIdSetIterator

        for (m in fc.getMatchingDocs()) {
            val numericDV = DocValues.getNumeric(m.context.reader(), "val")
            val liveDocs = m.context.reader().liveDocs
            // Only use the liveDocsDISI if liveDocs is not null
            disi = if (liveDocs == null) numericDV else FacetUtils.liveDocsDISI(numericDV, liveDocs)

            // Iterating over disi should only give values for live docs
            while (disi.nextDoc() != DocIdSetIterator.NO_MORE_DOCS) {
                visitedDocs++
                val `val` = numericDV.longValue().toInt()
                assertTrue(deletedDocs.get(`val`) == false, "Deleted doc ${`val`} found during iteration")
            }
        }

        assertTrue(
            visitedDocs == maxDocs - actualDocsDeleted,
            "Visited document [$visitedDocs] != Live documents [${maxDocs - actualDocsDeleted}]"
        )
        writer.close()
        IOUtils.close(searcher.indexReader, dir)
    }
}
