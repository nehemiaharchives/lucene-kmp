import org.gnit.lucenekmp.queryparser.flexible.standard.parser.StandardSyntaxParser
import org.gnit.lucenekmp.search.Query

/**
 * This pipeline has all the processors needed to process a query node tree, generated by
 * [StandardSyntaxParser], already assembled. <br>
 * <br>
 * The order they are assembled affects the results. <br>
 * <br>
 * This processor pipeline was designed to work with [StandardQueryConfigHandler]. <br>
 * <br>
 * The result query node tree can be used to build a [Query] object using
 * [StandardQueryTreeBuilder].
 *
 * @see StandardQueryTreeBuilder
 * @see StandardQueryConfigHandler
 * @see StandardSyntaxParser
 */
open class StandardQueryNodeProcessorPipeline(queryConfig: QueryConfigHandler?) :
    QueryNodeProcessorPipeline() {

    init {
        this.queryConfigHandler = queryConfig
        add(WildcardQueryNodeProcessor())
        add(MultiFieldQueryNodeProcessor())
        add(FuzzyQueryNodeProcessor())
        add(RegexpQueryNodeProcessor())
        add(MatchAllDocsQueryNodeProcessor())
        add(OpenRangeQueryNodeProcessor())
        add(PointQueryNodeProcessor())
        add(PointRangeQueryNodeProcessor())
        add(TermRangeQueryNodeProcessor())
        add(AllowLeadingWildcardProcessor())
        add(AnalyzerQueryNodeProcessor())
        add(PhraseSlopQueryNodeProcessor())
        // add(new GroupQueryNodeProcessor());
        add(BooleanQuery2ModifierNodeProcessor())
        add(NoChildOptimizationQueryNodeProcessor())
        add(RemoveDeletedQueryNodesProcessor())
        add(RemoveEmptyNonLeafQueryNodeProcessor())
        add(BooleanSingleChildOptimizationQueryNodeProcessor())
        add(DefaultPhraseSlopQueryNodeProcessor())
        add(BoostQueryNodeProcessor())
        add(MultiTermRewriteMethodProcessor())
        add(IntervalQueryNodeProcessor())
    }
}
